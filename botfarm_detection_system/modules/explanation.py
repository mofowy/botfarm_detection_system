def explain_cluster(cluster_id):
    """
    Формує просте пояснення результату для акаунта.
    """

    if cluster_id == -1:
        return (
            "Акаунт не увійшов до вираженої підозрілої групи "
            "за текстовою схожістю."
        )

    return (
        "Акаунт має текстову схожість з іншими профілями цієї групи "
        "та потребує додаткової перевірки."
    )


def mark_suspicious(cluster_id):
    """
    Позначає акаунт як потенційно підозрілий,
    якщо він належить до знайденого кластера.
    """

    return cluster_id != -1